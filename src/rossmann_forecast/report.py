"""Turn the results dictionary into docs/RESULTS.md, figures and the README results block.

Every number in the generated files comes from `summary`; nothing is typed by hand.
"""

from __future__ import annotations

import re
from pathlib import Path

import numpy as np
import pandas as pd

from .data import Panel

NAMES = {
    "naive_last": "Copy the last open day",
    "snaive": "Same weekday last week",
    "snaive_mean4": "Average of the same weekday over the last 4 weeks",
    "last_year": "Same weekday last year",
    "random_forest": "Random Forest",
    "lightgbm": "LightGBM (our model)",
    "prophet_plain": "Prophet, one model per store",
    "prophet_promo": "Prophet per store, also told promos and holidays",
}
RULE_PHRASE = {
    "naive_last": "copying the last open day",
    "snaive": "repeating the same weekday from last week",
    "snaive_mean4": "the average of the same weekday over the last four weeks",
    "last_year": "the same weekday one year earlier",
}
README_START = "<!-- RESULTS:START -->"
README_END = "<!-- RESULTS:END -->"


def _pm(entry: dict, metric: str, pct: bool = False) -> str:
    m, s = entry["mean"][metric], entry["std"][metric]
    if pct:
        return f"{m * 100:.1f}% +/- {s * 100:.1f}"
    if metric == "rmspe":
        return f"{m:.3f} +/- {s:.3f}"
    return f"{m:,.0f} +/- {s:,.0f}"


def _table(headers: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def _main_table(models: dict, order: list[str]) -> str:
    rows = []
    for name in order:
        if name not in models:
            continue
        e = models[name]
        label = f"**{NAMES[name]}**" if name == "lightgbm" else NAMES[name]
        rows.append([label, _pm(e, "wape", True), _pm(e, "rmse"), _pm(e, "mae"), _pm(e, "rmspe")])
    return _table(["Model", "Average error (WAPE, % of sales)", "RMSE", "MAE", "RMSPE"], rows)


def plain_english(summary: dict) -> str:
    models = summary["all_stores"]
    lgb = models["lightgbm"]
    rules = [m for m in RULE_PHRASE if m in models]
    best_name = min(rules, key=lambda m: models[m]["mean"]["wape"])
    best = models[best_name]
    weeks = summary["meta"]["horizon_days"] // 7
    n_folds = len(summary["folds"])
    gain = (1 - lgb["mean"]["wape"] / best["mean"]["wape"]) * 100
    return (
        f"This project predicts how much each Rossmann store will sell on each day for the next "
        f"{weeks} weeks, so managers can plan staff and stock. "
        f"It was tested on {n_folds} separate {weeks}-week periods that the model had never seen: "
        f"for each period it learned only from sales before it began. "
        f"On a typical store-day the forecast is off by {lgb['mean']['wape'] * 100:.1f}% of sales, "
        f"compared with {best['mean']['wape'] * 100:.1f}% for the best simple rule "
        f"({RULE_PHRASE[best_name]}), a {gain:.0f}% reduction in error."
    )


def results_markdown(summary: dict) -> str:
    meta, folds = summary["meta"], summary["folds"]
    order = ["naive_last", "snaive", "snaive_mean4", "last_year", "random_forest", "lightgbm"]
    out = []
    out.append("# Results\n")
    out.append(
        "Generated by `rossmann run-all` (see Makefile). Do not edit by hand; every number below "
        "is written by code from `reports/results.json`.\n"
    )
    out.append(
        f"Run: commit `{meta['git_commit']}`, Python {meta['versions']['python']}, "
        f"pandas {meta['versions']['pandas']}, LightGBM {meta['versions']['lightgbm']}, "
        f"seed {meta['seed']}. Total runtime {summary['total_runtime_seconds'] / 60:.1f} minutes "
        f"on the machine that produced these numbers.\n"
    )
    out.append("## In plain English\n")
    out.append(plain_english(summary) + "\n")
    out.append("## Evaluation design\n")
    out.append(
        f"* Task: forecast daily sales of every open store for the next {meta['horizon_days']} days, "
        "using only sales observed before the forecast origin. Promo calendar, holidays and "
        "open/closed flags for the target dates are treated as known in advance.\n"
        f"* Data: {meta['n_stores']:,} stores, {meta['data_start']} to {meta['data_end']}. "
        "Rows with the store closed or zero sales are not scored (as in the Kaggle metric).\n"
        "* Rolling origin, expanding window: each fold fits on everything before its origin and "
        "predicts the next window. Sales-derived features are lagged by at least the horizon.\n"
        "* Mean +/- standard deviation (n-1) are over folds; each fold metric is computed over all "
        "scored store-days in that fold.\n"
    )
    fold_rows = [
        [
            str(f["fold"]), f["test_start"], f["test_end"], f"{f['n_scored_rows']:,}",
            f"{f['n_stores']:,}", f"{f['mean_daily_sales']:,.0f}",
        ]
        for f in folds
    ]  # fmt: skip
    out.append(
        _table(
            [
                "Fold",
                "Forecast from",
                "Forecast to",
                "Scored store-days",
                "Stores",
                "Mean daily sales",
            ],
            fold_rows,
        )
        + "\n"
    )

    out.append("## All stores: point forecasts\n")
    out.append(
        "The headline measure is the average error as a percent of sales (WAPE: total absolute error "
        "divided by total sales). The other three columns are standard alternatives: MAE is the "
        "average miss in sales units per store per day; RMSE is similar but punishes big misses "
        "more; RMSPE is the Kaggle competition measure, a percentage version of RMSE. "
        "Lower is better for all of them.\n"
    )
    out.append(_main_table(summary["all_stores"], order) + "\n")
    out.append("Per fold (WAPE % / RMSE):\n")
    rows = []
    for name in order:
        if name not in summary["all_stores"]:
            continue
        cells = [NAMES[name]]
        for pf in summary["all_stores"][name]["per_fold"]:
            cells.append(f"{pf['wape'] * 100:.1f} / {pf['rmse']:,.0f}")
        rows.append(cells)
    out.append(
        _table(["Model"] + [f"Fold {f['fold']} ({f['test_start']})" for f in folds], rows) + "\n"
    )

    if "sample_stores" in summary:
        n = meta["n_prophet_stores"]
        out.append(f"## Per-store Prophet versus the global model ({n}-store random sample)\n")
        out.append(
            f"Prophet is fitted separately per store and per fold, so it is run on a fixed random "
            f"sample of {n} stores (seed {meta['seed']}), not all {meta['n_stores']:,}. "
            "All rows below are scored on exactly the same store-days.\n"
        )
        order_s = order + ["prophet_plain", "prophet_promo"]
        out.append(_main_table(summary["sample_stores"], order_s) + "\n")

    se = summary["store_error"]
    out.append("## How error is spread across stores\n")
    out.append(
        f"Store-level WAPE for each of the {se['n_store_folds']:,} (store, fold) pairs. "
        "A good average can hide bad stores, so the tail is shown.\n"
    )
    q = se["wape_quantiles"]
    rows = []
    for m in ("lightgbm", "last_year", "snaive_mean4"):
        rows.append(
            [NAMES[m]] + [f"{q[m][k] * 100:.1f}%" for k in ("p10", "p50", "p90", "p99", "max")]
        )
    out.append(_table(["Model", "p10", "median", "p90", "p99", "max"], rows) + "\n")
    beats = se["share_store_folds_lightgbm_beats"]
    out.append(
        "Share of (store, fold) pairs where LightGBM has lower WAPE than: "
        + "; ".join(f"{NAMES[k].lower()} {v * 100:.0f}%" for k, v in beats.items())
        + ".\n"
    )
    worst = ", ".join(
        f"store {w['store']} ({w['wape'] * 100:.0f}% WAPE, mean sales {w['mean_sales']:,.0f})"
        for w in se["worst_stores"]
    )
    out.append(f"Five worst stores by mean WAPE: {worst}.\n")
    out.append("![Store error histogram](../reports/figures/store_wape_hist.png)\n")

    out.append("## Prediction intervals (split conformal, log scale)\n")
    out.append(
        "Intervals are the LightGBM forecast +/- a conformal quantile of absolute log errors. "
        "Calibration residuals come from a model refitted one horizon earlier and scored on the "
        "window just before each forecast origin, so no calibration row overlaps a test window.\n"
    )
    rows = []
    for tag, block in summary["intervals"].items():
        for pf in block["per_fold"]:
            rows.append(
                [
                    f"{tag}%", str(pf["fold"]), f"{pf['coverage'] * 100:.1f}%",
                    f"{pf['mean_width']:,.0f}", f"{pf['median_relative_width'] * 100:.0f}%",
                ]
            )  # fmt: skip
        rows.append([f"{tag}%", "all", f"{block['overall_coverage'] * 100:.1f}%", "", ""])
    out.append(
        _table(
            [
                "Nominal",
                "Fold",
                "Empirical coverage",
                "Mean width (sales units)",
                "Median width / forecast",
            ],
            rows,
        )
        + "\n"
    )
    b90 = summary["intervals"]["90"]
    out.append(
        "90% interval coverage by forecast day: "
        + "; ".join(f"{k} {v * 100:.1f}%" for k, v in b90["coverage_by_horizon"].items())
        + ". Per (store, fold) coverage quantiles p10 / p50 / p90: "
        + " / ".join(f"{v * 100:.0f}%" for v in b90["per_store_fold_coverage_quantiles"].values())
        + f"; {b90['share_store_folds_within_10pts'] * 100:.0f}% of store-folds are within 10 points "
        "of nominal.\n"
    )
    out.append("![Example forecast](../reports/figures/forecast_example.png)\n")

    out.append("## Promotion effect (association, not a validated causal estimate)\n")
    fe = summary["promo_fixed_effects"]
    out.append(
        "Promos are scheduled by the retailer, not randomised, and in this data the whole chain "
        "follows one promo calendar (alternate Monday-to-Friday weeks): every store has the same "
        "promo flag on a given date. So there is no same-day control group, a date fixed effect "
        "absorbs the promo entirely, and the effect is identified only from week-to-week "
        "alternation. It cannot be separated from anything else that alternates with the promo "
        "weeks. Read both estimates below as associations, not proven causal effects.\n"
    )
    rows = [
        [
            f"Model counterfactual, fold {r['fold']}",
            f"{r['lift_pct']:+.1f}%", "none (see note)",
            f"{r['mean_extra_sales_per_promo_day']:,.0f}", str(r["n_promo_weeks"]),
        ]
        for r in summary["promo_model_counterfactual"]
    ]  # fmt: skip
    rows.append(
        [
            "Fixed effects: store x weekday, year-month, holiday controls; all data",
            f"{fe['lift_pct']:+.1f}%", f"{fe['ci95_low_pct']:+.1f}% to {fe['ci95_high_pct']:+.1f}%",
            "", str(fe["n_week_clusters"]),
        ]
    )  # fmt: skip
    out.append(
        _table(
            [
                "Estimate",
                "Lift on promo days",
                "95% interval",
                "Extra sales per promo day",
                "Calendar weeks",
            ],
            rows,
        )
        + "\n"
    )
    out.append(
        f"Raw ratio of mean sales (promo days / other open days) minus 1: {fe['naive_ratio_lift_pct']:+.1f}%. "
        "The model counterfactual flips only the promo flag of the fitted global model on the "
        "promoted days of each forecast window, leaving neighbouring-day promo features unchanged, so it "
        "is not an independent check on the regression and can differ from it; it has no interval because a window holds only a "
        "few independent promo weeks and every store shares them, so a bootstrap over stores would "
        "overstate precision. The fixed-effects interval uses standard errors clustered by "
        "calendar week, the level at which the promo varies.\n"
    )
    out.append(
        f"Randomisation check: permuting whole promo weeks among the weeks of the same month "
        f"{fe['n_permutations']} times gave a spread (standard deviation) of the log-effect of "
        f"{fe['permutation_beta_sd']:.4f}, largest absolute value {fe['permutation_beta_abs_max']:.4f}, "
        f"against the real estimate of {fe['beta_log']:+.4f}; randomisation p-value "
        f"{fe['permutation_p_value']:.3f}. This checks the estimate is not what shuffled promo "
        "weeks would produce; it does not rule out a confounder that alternates with the promo.\n"
    )
    out.append(
        "Assumptions: within a month, which weeks are promo weeks is unrelated to other demand "
        "drivers; no store-specific timing; no stockpiling or post-promo dip is modelled (the "
        "estimate is the average difference between promo and non-promo days, not a net effect "
        "over time); customer counts are not controlled for because they are a consequence of "
        "the promo.\n"
    )

    out.append("## Feature attribution (SHAP, final fold model)\n")
    out.append(
        "Mean absolute SHAP value on 5,000 sampled forecast rows, in log1p(sales) units. "
        "This explains the model's predictions, not causes in the world.\n"
    )
    rows = [[k, f"{v:.4f}"] for k, v in summary["shap_top"].items()]
    out.append(_table(["Feature", "Mean abs SHAP"], rows) + "\n")
    out.append("![SHAP summary](../reports/figures/shap_summary.png)\n")

    out.append("## Training cost\n")
    rows = []
    for fold_key, timings in summary["timing_seconds"].items():
        rows.append(
            [
                fold_key.replace("fold", "Fold "),
                f"{timings['lightgbm_fit']:.0f}",
                f"{timings.get('random_forest_fit', float('nan')):.0f}",
                f"{timings.get('prophet_plain_fit_per_store', float('nan')):.2f}",
                f"{timings.get('prophet_promo_fit_per_store', float('nan')):.2f}",
            ]
        )
    out.append(
        _table(
            [
                "Fold",
                "LightGBM, all stores (s)",
                "Random Forest, all stores (s)",
                "Prophet plain, per store (s)",
                "Prophet + regressors, per store (s)",
            ],
            rows,
        )  # fmt: skip
        + "\n"
    )
    out.append(
        "One LightGBM fit covers every store; Prophet needs one fit per store, so its cost scales "
        "with the number of stores. Seconds are wall-clock on the machine that ran the pipeline.\n"
    )
    return "\n".join(out)


def readme_block(summary: dict) -> str:
    order = ["naive_last", "snaive_mean4", "last_year", "random_forest", "lightgbm"]
    models = summary["all_stores"]
    iv = summary["intervals"]["90"]
    sample = summary.get("sample_stores")
    rows = []
    for name in order:
        if name not in models:
            continue
        e = models[name]
        label = f"**{NAMES[name]}**" if name == "lightgbm" else NAMES[name]
        cell = f"{e['mean']['wape'] * 100:.1f}% (+/- {e['std']['wape'] * 100:.1f})"
        rows.append([label, f"**{cell}**" if name == "lightgbm" else cell])
    cover = iv["overall_coverage"] * 100
    gap = 90 - cover
    if gap <= 0:
        verdict = "on target or better"
    elif gap <= 5:
        verdict = "a little under the 90% target"
    else:
        verdict = "well under the 90% target"
    lines = [
        README_START,
        f"_Generated by code from `reports/results.json` (commit `{summary['meta']['git_commit']}`)._",
        "",
        plain_english(summary),
        "",
        _table(["Method", "Average error (% of sales)"], rows),
        "",
        "Lower is better. An average error of 9% means the forecasts missed the real sales by about "
        '9% of sales, adding up all store-days. The number after "+/-" shows how much the result '
        f"varied between the {len(summary['folds'])} test periods: a small value means the method "
        "was steady, a large one means it did well in some periods and badly in others.",
        "",
    ]
    if sample:
        n = summary["meta"]["n_prophet_stores"]
        lines += [
            f"Prophet, a popular forecasting tool that fits one model per store, is slow to run for "
            f"every store, so it was tried on a random sample of {n} stores. On those stores it was "
            f"off by {sample['prophet_plain']['mean']['wape'] * 100:.1f}% on its own and "
            f"{sample['prophet_promo']['mean']['wape'] * 100:.1f}% when also given the promotion and "
            f"holiday calendar, against {sample['lightgbm']['mean']['wape'] * 100:.1f}% for LightGBM "
            "on the same stores.",
            "",
        ]
    per_period = ", ".join(f"{p['coverage'] * 100:.1f}%" for p in iv["per_fold"])
    lines += [
        "Each forecast also comes with a 90% prediction range, meant to contain the true sales nine "
        f"times out of ten. In the tests the range held the true sales {cover:.1f}% of the time, "
        f"{verdict} ({per_period} in the three test periods).",
        "",
        "Other error measures (RMSE, MAE and RMSPE), error by store, the promotion analysis and "
        "feature importance are in [docs/RESULTS.md](docs/RESULTS.md).",
        README_END,
    ]
    return "\n".join(lines)


def _figures(
    panel: Panel, preds: pd.DataFrame, store_frame: pd.DataFrame, out_dir: Path, summary: dict
) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig_dir = out_dir / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)

    fig, ax = plt.subplots(figsize=(7, 4))
    vals = store_frame["lightgbm"].clip(upper=store_frame["lightgbm"].quantile(0.995)) * 100
    ax.hist(vals, bins=60, color="#3b6ea5")
    ax.axvline(store_frame["lightgbm"].median() * 100, color="k", ls="--", label="median")
    ax.set_xlabel("Store-level WAPE (%), one value per store and fold")
    ax.set_ylabel("Count")
    ax.set_title("Spread of LightGBM error across stores")
    ax.legend()
    fig.tight_layout()
    fig.savefig(fig_dir / "store_wape_hist.png", dpi=130)
    plt.close(fig)

    last = preds[preds["fold"] == preds["fold"].max()]
    mean_sales = last.groupby("store_id")["y"].mean()
    store = int((mean_sales - mean_sales.median()).abs().idxmin())
    g = last[last["store_id"] == store].sort_values("date")
    j = int(np.where(panel.stores == store)[0][0])
    hist = panel.sales.iloc[:, j].loc[: g["date"].min() - pd.Timedelta(days=1)].dropna().tail(60)
    fig, ax = plt.subplots(figsize=(9, 4))
    ax.plot(hist.index, hist.values, color="#888", label="history")
    ax.plot(g["date"], g["y"], "o-", ms=3, color="k", label="actual")
    ax.plot(g["date"], g["lightgbm"], color="#c0392b", label="LightGBM forecast")
    ax.fill_between(
        g["date"], g["lo90"], g["hi90"], color="#c0392b", alpha=0.2, label="90% interval"
    )
    ax.plot(g["date"], g["last_year"], color="#2e8b57", ls=":", label="last year same weekday")
    ax.set_title(f"Store {store}, final fold: forecast made before {g['date'].min().date()}")
    ax.set_ylabel("Daily sales")
    ax.legend(ncol=3, fontsize=8)
    fig.autofmt_xdate()
    fig.tight_layout()
    fig.savefig(fig_dir / "forecast_example.png", dpi=130)
    plt.close(fig)

    models = summary["all_stores"]
    order = [m for m in NAMES if m in models and not m.startswith("prophet")]
    order.sort(key=lambda m: -models[m]["mean"]["wape"])
    palette = {"lightgbm": "#c0392b", "random_forest": "#d98324", "last_year": "#2e8b57",
               "snaive_mean4": "#8e6bbf", "snaive": "#7f7f7f", "naive_last": "#bcbd22"}  # fmt: skip
    fig, ax = plt.subplots(figsize=(10, 3.8))
    vals = [models[m]["mean"]["wape"] * 100 for m in order]
    errs = [models[m]["std"]["wape"] * 100 for m in order]
    ax.barh(
        [NAMES[m] for m in order], vals, xerr=errs, color=[palette[m] for m in order], capsize=3
    )
    for i, v in enumerate(vals):
        ax.text(v + errs[i] + 0.5, i, f"{v:.1f}%", va="center")
    ax.set_xlabel("Average error (% of sales): lower is better")
    ax.set_title("One ML model roughly halves the error of simple rules")
    fig.tight_layout()
    fig.savefig(fig_dir / "model_comparison.png", dpi=130)
    plt.close(fig)

    chain = last.groupby("date")[["y", "lightgbm"]].sum() / 1e6
    chain_wape = (chain["y"] - chain["lightgbm"]).abs().sum() / chain["y"].sum() * 100
    fig, ax = plt.subplots(figsize=(9, 3.6))
    ax.plot(chain.index, chain["y"], "o-", color="black", ms=3, lw=1, label="actual")
    ax.plot(
        chain.index,
        chain["lightgbm"],
        color="#c0392b",
        lw=2.2,
        label="forecast made 6 weeks earlier",
    )
    ax.set_ylabel("Sales, all stores (millions per day)")
    ax.set_title(f"Whole chain, final test window: daily forecast error {chain_wape:.1f}%")
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.18), ncol=2)
    fig.autofmt_xdate()
    fig.tight_layout()
    fig.savefig(fig_dir / "chain_forecast.png", dpi=130)
    plt.close(fig)


def write_reports(
    panel: Panel,
    preds: pd.DataFrame,
    store_frame: pd.DataFrame,
    summary: dict,
    *,
    out_dir: str | Path = "reports",
    docs_dir: str | Path = "docs",
    readme: str | Path | None = "README.md",
) -> None:
    out_dir, docs_dir = Path(out_dir), Path(docs_dir)
    docs_dir.mkdir(parents=True, exist_ok=True)
    _figures(panel, preds, store_frame, out_dir, summary)
    (docs_dir / "RESULTS.md").write_text(results_markdown(summary), encoding="utf-8")
    if readme is not None and Path(readme).exists():
        text = Path(readme).read_text(encoding="utf-8")
        if README_START in text and README_END in text:
            pattern = re.compile(re.escape(README_START) + ".*?" + re.escape(README_END), re.DOTALL)
            text = pattern.sub(lambda _: readme_block(summary), text)
            Path(readme).write_text(text, encoding="utf-8")
